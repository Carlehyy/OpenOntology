#!/usr/bin/env bash
# Isolated real-backend E2E stack for the ontology-assistant workflow.
#
# stack-up / stack-down / stack-status manage the five docker-compose.e2e.yml
# infrastructure services under an independent compose project with
# loopback-only offset ports (never touches other compose projects, images are
# never pulled). migrate-verify checks the Alembic story: single head, fresh
# upgrade, and a legacy-baseline database with deterministic data upgraded to
# head; each run uses its own UUID-suffixed databases that are removed again,
# and writes a JSON report into .artifacts. backend-up/backend-down run the
# real backend from this checkout on 127.0.0.1:18036 with fixture credentials
# only (env -i, no personal or production env files); readiness is reported
# honestly - n8n / Chromium CDP absence keeps /health/ready at 503.
# executor-up/executor-down run this checkout's NATS executor with the same
# fixture env so ontology-assistant background runs are actually consumed.
#
# All generated state lives in <repo>/.artifacts/real-stack-e2e/ (gitignored).
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
BACKEND_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
REPO_DIR="$(cd "$BACKEND_DIR/.." && pwd)"

COMPOSE_PROJECT="${COMPOSE_PROJECT:-yiya36-fixes}"
ART="$REPO_DIR/.artifacts/real-stack-e2e"
OVERRIDE_FILE="$ART/docker-compose.override.yml"
BACKEND_LOG="$ART/backend.log"
BACKEND_PID="$ART/backend.pid"
BACKEND_CMD="$ART/backend.cmd"
EXECUTOR_LOG="$ART/nats_executor.log"
EXECUTOR_PID="$ART/nats_executor.pid"
EXECUTOR_CMD="$ART/nats_executor.cmd"
REPORT="$ART/migrate-verify-report.json"
BACKEND_PORT="${BACKEND_PORT:-18036}"

PG_PORT=25432
REDIS_PORT=26379
NATS_PORT=24222
NEO4J_HTTP_PORT=27474
NEO4J_BOLT_PORT=27687
MINIO_API_PORT=29000
MINIO_CONSOLE_PORT=29001

BASELINE_REV="${BASELINE_REV:-0129_scheduled_task_target}"

PG_CONTAINER="${COMPOSE_PROJECT}-db-1"
NATS_CONTAINER="${COMPOSE_PROJECT}-nats-1"
PG_USER=ontoprompt
PG_PASSWORD=ontoprompt  # fixture credential, identical to docker-compose.e2e.yml

log() { printf '[real-stack-e2e] %s\n' "$*"; }
die() { printf '[real-stack-e2e] ERROR: %s\n' "$*" >&2; exit 1; }

ensure_override() {
  mkdir -p "$ART"
  [ -f "$OVERRIDE_FILE" ] && return 0
  cat > "$OVERRIDE_FILE" <<YAML
# Generated by backend/scripts/ontology_assistant_real_stack_e2e.sh.
# Rebinds docker-compose.e2e.yml ports to loopback-only offset ports under the
# independent compose project ${COMPOSE_PROJECT}; pull_policy never keeps the
# existing local images (no registry access). Named volumes resolve per
# compose project, so this stack's volumes are isolated from other projects.
name: ${COMPOSE_PROJECT}
services:
  db:
    pull_policy: never
    mem_limit: 512m
    ports: !override
      - "127.0.0.1:${PG_PORT}:5432"
  redis:
    pull_policy: never
    mem_limit: 96m
    ports: !override
      - "127.0.0.1:${REDIS_PORT}:6379"
  nats:
    pull_policy: never
    mem_limit: 96m
    ports: !override
      - "127.0.0.1:${NATS_PORT}:4222"
  neo4j:
    pull_policy: never
    mem_limit: 1280m
    ports: !override
      - "127.0.0.1:${NEO4J_HTTP_PORT}:7474"
      - "127.0.0.1:${NEO4J_BOLT_PORT}:7687"
  minio:
    pull_policy: never
    mem_limit: 256m
    ports: !override
      - "127.0.0.1:${MINIO_API_PORT}:9000"
      - "127.0.0.1:${MINIO_CONSOLE_PORT}:9001"
YAML
  log "wrote compose override $OVERRIDE_FILE"
}

compose() {
  docker compose -p "$COMPOSE_PROJECT" \
    -f "$REPO_DIR/docker-compose.e2e.yml" \
    -f "$OVERRIDE_FILE" "$@"
}

port_free() { ! lsof -nP -iTCP:"$1" -sTCP:LISTEN >/dev/null 2>&1; }

stack_up() {
  ensure_override
  local p
  for p in "$PG_PORT" "$REDIS_PORT" "$NATS_PORT" "$NEO4J_HTTP_PORT" \
           "$NEO4J_BOLT_PORT" "$MINIO_API_PORT" "$MINIO_CONSOLE_PORT"; do
    port_free "$p" || die "port $p already in use; refusing to start"
  done
  compose up -d --wait
  docker ps --filter "label=com.docker.compose.project=$COMPOSE_PROJECT" \
    --format '{{.Names}}  {{.Status}}  {{.Ports}}'
}

stack_down() {
  local volumes=""
  [ "${1:-}" = "-v" ] && volumes="-v"
  compose down $volumes
  log "stack down (volumes flag: '${volumes:-none}')"
}

stack_status() { compose ps; }

psql_admin() {  # psql_admin <database> ; reads SQL from stdin
  docker exec -i "$PG_CONTAINER" \
    psql -U "$PG_USER" -d "$1" -v ON_ERROR_STOP=1 "${@:2}"
}

