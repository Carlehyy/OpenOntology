run_alembic() {  # run_alembic <database> <args...>
  local db="$1"; shift
  (cd "$BACKEND_DIR" && alembic_env "$db" uv run alembic "$@")
}

# Per-run UUID-suffixed databases; the trap removes only what this run created.
CREATED_DBS=()
cleanup_dbs() {
  local db
  for db in "${CREATED_DBS[@]}"; do
    docker exec "$PG_CONTAINER" psql -U "$PG_USER" -d ontoprompt -qc \
      "DROP DATABASE IF EXISTS \"$db\"" >/dev/null 2>&1 || true
  done
  [ "${#CREATED_DBS[@]}" -gt 0 ] && log "removed run databases: ${CREATED_DBS[*]}"
}

create_run_db() {  # create_run_db <var-name> <prefix>
  local db
  db="$2_$(uuidgen | tr 'A-Z' 'a-z' | cut -c1-8)"
  docker exec "$PG_CONTAINER" psql -U "$PG_USER" -d ontoprompt -v ON_ERROR_STOP=1 -qc \
    "CREATE DATABASE \"$db\""
  CREATED_DBS+=("$db")
  printf -v "$1" '%s' "$db"
}

json_escape() { printf '%s' "$1" | sed 's/\\/\\\\/g; s/"/\\"/g'; }

