    || { log 'FAIL fresh and upgraded schemas differ'; fail_count=$((fail_count+1)); }

  {
    printf '{"run_id":"%s","timestamp":"%s","head":"%s","baseline":"%s",\n' \
      "$run_id" "$ts" "$head_rev" "$BASELINE_REV"
    printf ' "fresh_db":"%s","legacy_db":"%s",\n' "$fresh_db" "$legacy_db"
    printf ' "passed_checks":[%s],\n' "${pass_lines%,}"
    printf ' "failed_checks":[%s],\n' "${fail_lines%,}"
    printf ' "write_probe":"pass","schema_diff_identical":%s,\n' "$schema_identical"
    printf ' "status":"%s"}\n' "$([ $fail_count -eq 0 ] && echo passed || echo failed)"
  } > "$REPORT"
  log "report written to $REPORT"
  [ "$fail_count" -eq 0 ] || die "migrate-verify failed ($fail_count checks)"
  log 'migrate-verify OK'
}

build_backend_launch_env() {
  # Fixture-only environment assignments; env -i blocks personal env files.
  # Optional untracked overrides for deep-readiness dependencies (a real n8n
  # instance + API key and a Chromium CDP URL). The file lives in
  # .artifacts/real-stack-e2e/n8n.env and is never committed; without it the
  # backend boots with advisory n8n/CDP settings and /health/ready stays 503.
  local n8n_url=http://127.0.0.1:5678 n8n_key=e2e-dummy-n8n-key \
        cdp_url=http://localhost:9222 k v
  # Forward only explicitly provided run-ledger overrides (for example
  # AGENT_RUN_LEASE_SECONDS=30 in a restart/reconcile drill). Production
  # defaults remain in backend/app/ontologies/agent_runtime/limits.py.
  local run_env=()
  for k in AGENT_RUN_USER_CAP AGENT_RUN_GLOBAL_CAP AGENT_RUN_LEASE_SECONDS \
           AGENT_RUN_EVENT_POLL_MS AGENT_RUN_HEARTBEAT_SECONDS \
           AGENT_RUN_DELTA_FLUSH_MS AGENT_RUN_DELTA_FLUSH_CHARS \
           AGENT_RUN_QUEUE_CAP AGENT_RUN_EVENT_PAYLOAD_CAP \
           AGENT_RUN_EVENT_RETENTION_HOURS AGENT_CONTEXT_CHARS_CAP \
           AGENT_LLM_TIMEOUT_SECONDS INTEGRATED_DBX_URL \
           INTEGRATED_DBX_PASSWORD INTEGRATED_DBX_COMMIT \
           WEKNORA_BASE_URL WEKNORA_WEB_URL; do
    if [ -n "${!k-}" ]; then
      run_env+=("$k=${!k}")
    fi
  done
  if [ -f "$ART/n8n.env" ]; then
    while IFS='=' read -r k v; do
      case "$k" in
        N8N_API_URL) n8n_url="$v" ;;
        N8N_API_KEY) n8n_key="$v" ;;
        STEWARD_BROWSER_CDP_URL) cdp_url="$v" ;;
      esac
    done < "$ART/n8n.env"
    log "using deep-readiness overrides from $ART/n8n.env"
  fi
  BACKEND_LAUNCH_ENV=(
    HOME="$HOME" PATH="$PATH" PYTHONUNBUFFERED=1
    ENVIRONMENT=development
