backend_up() {
  docker inspect "$PG_CONTAINER" >/dev/null 2>&1 \
    || die "stack not running; run '$0 stack-up' first"
  [ -x "$BACKEND_DIR/.venv/bin/python" ] \
    || die "backend .venv missing; run 'uv sync --frozen --group dev' in backend/"
  port_free "$BACKEND_PORT" || die "port $BACKEND_PORT already in use"
  mkdir -p "$ART"

  log "applying alembic upgrade head to backend database"
  run_alembic ontoprompt upgrade head >/dev/null

  # Plain uvicorn (no reload reloader tree) on this checkout's venv python.
  # Backgrounding a simple command keeps the recorded pid identical to the
  # server process (nohup and env both exec, nothing is left in between).
  build_backend_launch_env
  ( cd "$BACKEND_DIR"
    nohup env -i "${BACKEND_LAUNCH_ENV[@]}" \
      "$BACKEND_DIR/.venv/bin/python" -m uvicorn app.main:app \
      --host 127.0.0.1 --port "$BACKEND_PORT" > "$BACKEND_LOG" 2>&1 &
    echo $! > "$BACKEND_PID"
  )
  local pid
  pid=$(cat "$BACKEND_PID")
  log "backend starting (pid $pid)"

  local i
  for i in $(seq 1 90); do
    if curl -sf -o /dev/null "http://127.0.0.1:$BACKEND_PORT/health/live"; then
      ps -p "$pid" -o command= > "$BACKEND_CMD" \
        || die "backend process exited before readiness"
      log "backend LIVE: http://127.0.0.1:$BACKEND_PORT (log: $BACKEND_LOG)"
      local ready_code ready_body
      ready_code=$(curl -s -o "$ART/health-ready.json" -w '%{http_code}' \
        "http://127.0.0.1:$BACKEND_PORT/health/ready" || true)
      ready_body="$(head -c 400 "$ART/health-ready.json" 2>/dev/null || true)"
      if [ "$ready_code" = "200" ]; then
        log "backend READY (/health/ready 200)"
      else
        log "WARNING: /health/ready returned $ready_code (deep readiness not satisfied; e.g. n8n / Chromium CDP unreachable). Body: $ready_body"
        log "API is reachable and serves requests, but flows needing those dependencies will fail until they are provided."
      fi
      log "admin login: admin / admin123 (fixture seed)"
      return 0
    fi
    if ! kill -0 "$pid" 2>/dev/null; then
      log "backend process exited early; last log lines:"
      tail -30 "$BACKEND_LOG" || true
      rm -f "$BACKEND_PID" "$BACKEND_CMD"
      die "backend failed to start"
    fi
    sleep 2
  done
  # Own process cleanup on timeout - never leave orphans behind.
  kill "$pid" 2>/dev/null || true
  sleep 2
  kill -9 "$pid" 2>/dev/null || true
  rm -f "$BACKEND_PID" "$BACKEND_CMD"
  die "backend did not become live within 180s; inspect $BACKEND_LOG"
}

backend_down() {
  local pid cmd
  if [ -f "$BACKEND_PID" ]; then
    pid=$(cat "$BACKEND_PID")
    if kill -0 "$pid" 2>/dev/null; then
      cmd=$(ps -p "$pid" -o command=)
      [ -f "$BACKEND_CMD" ] && [ "$cmd" = "$(cat "$BACKEND_CMD")" ] \
        || die "pid $pid no longer matches the recorded backend; refusing to kill"
      kill "$pid"
      local _
      for _ in $(seq 1 20); do kill -0 "$pid" 2>/dev/null || break; sleep 1; done
      kill -0 "$pid" 2>/dev/null && kill -9 "$pid" || true
      log "backend pid $pid stopped"
    else
      log "recorded backend pid $pid is not running"
    fi
    rm -f "$BACKEND_PID" "$BACKEND_CMD"
  else
    log "no backend pid recorded"
  fi
  # Report only - never kill a listener we do not own.
  if ! port_free "$BACKEND_PORT"; then
    log "WARNING: port $BACKEND_PORT is still occupied by another process:"
    lsof -nP -iTCP:"$BACKEND_PORT" -sTCP:LISTEN || true
    die "port $BACKEND_PORT still occupied (not killed - not ours)"
  fi
  log "port $BACKEND_PORT released"
}

backend_status() {
  local pid
  if [ -f "$BACKEND_PID" ]; then
    pid=$(cat "$BACKEND_PID")
    if kill -0 "$pid" 2>/dev/null; then
      log "backend pid $pid running: $(ps -p "$pid" -o command=)"
    else
      log "recorded backend pid $pid not running"
    fi
  else
    log "no backend pid recorded"
  fi
  if port_free "$BACKEND_PORT"; then
    log "nothing listening on $BACKEND_PORT"
  else
    lsof -nP -iTCP:"$BACKEND_PORT" -sTCP:LISTEN
    log "live probe: $(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:$BACKEND_PORT/health/live" || echo unreachable)"
    log "ready probe: $(curl -s -o /dev/null -w '%{http_code}' "http://127.0.0.1:$BACKEND_PORT/health/ready" || echo unreachable)"
  fi
}

